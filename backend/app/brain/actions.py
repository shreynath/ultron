"""Typed, application-owned action models for the execution boundary.

Plan steps remain descriptive.  An ``ActionRequest`` is created by application
code only after a caller has selected one plan step and supplied an explicitly
supported operation and parameters.
"""
from __future__ import annotations

from enum import Enum
from typing import Any
from uuid import UUID, uuid4

from pydantic import BaseModel, ConfigDict, Field, model_validator

MAX_ACTION_PARAMETERS = 32
MAX_ACTION_OUTPUT_BYTES = 8_000


class ActionStatus(str, Enum):
    COMPLETED = "completed"
    REJECTED = "rejected"
    FAILED = "failed"
    UNSUPPORTED = "unsupported"
    TIMED_OUT = "timed_out"


class ActionErrorCode(str, Enum):
    INVALID_ACTION = "invalid_action"
    TASK_MISMATCH = "task_mismatch"
    CAPABILITY_NOT_ALLOWED = "capability_not_allowed"
    CAPABILITY_NOT_REGISTERED = "capability_not_registered"
    OPERATION_NOT_REGISTERED = "operation_not_registered"
    INVALID_PARAMETERS = "invalid_parameters"
    PREREQUISITE_NOT_SATISFIED = "prerequisite_not_satisfied"
    EXECUTION_FAILED = "execution_failed"
    EXECUTION_TIMEOUT = "execution_timeout"
    INTERNAL_ERROR = "internal_error"
    DUPLICATE_ACTION = "duplicate_action"


class ActionError(BaseModel):
    """A safe, stable error returned to the cognitive caller."""

    model_config = ConfigDict(extra="forbid")

    code: ActionErrorCode
    message: str = Field(min_length=1, max_length=500)


class ActionRequest(BaseModel):
    """One concrete operation that may be sent through the capability boundary."""

    model_config = ConfigDict(extra="forbid")

    # The default is generated by application code.  The builder below is the
    # production path; a supplied ID is never treated as authorization.
    action_id: UUID = Field(default_factory=uuid4)
    task_id: UUID
    capability: str = Field(min_length=1, max_length=64, pattern=r"^[a-z][a-z0-9_]*$")
    operation: str = Field(min_length=1, max_length=64, pattern=r"^[a-z][a-z0-9_]*$")
    parameters: dict[str, Any] = Field(default_factory=dict, max_length=MAX_ACTION_PARAMETERS)
    # Plan metadata is application-owned by ActionRequestBuilder.  It is used
    # solely to reject unsatisfied prerequisites; the executor never traverses
    # dependencies itself.
    plan_id: UUID | None = None
    plan_step_id: str | None = Field(default=None, pattern=r"^step_[1-9][0-9]*$", max_length=64)
    depends_on: tuple[str, ...] = Field(default=(), max_length=11)

    @model_validator(mode="after")
    def validate_plan_metadata(self) -> ActionRequest:
        if (self.plan_id is None) != (self.plan_step_id is None):
            raise ValueError("plan_id and plan_step_id must be supplied together")
        if self.depends_on and self.plan_id is None:
            raise ValueError("dependencies require application-owned plan metadata")
        if len(self.depends_on) != len(set(self.depends_on)):
            raise ValueError("dependencies must be unique")
        if self.plan_step_id is not None and self.plan_step_id in self.depends_on:
            raise ValueError("an action may not depend on itself")
        return self


class ActionResult(BaseModel):
    """The factual result of one executor invocation."""

    model_config = ConfigDict(extra="forbid")

    action_id: UUID
    task_id: UUID
    capability: str
    operation: str
    status: ActionStatus
    output: Any | None = None
    output_truncated: bool = False
    error: ActionError | None = None
    duration_ms: float = Field(ge=0)

    @model_validator(mode="after")
    def validate_status_shape(self) -> ActionResult:
        if self.status is ActionStatus.COMPLETED and self.error is not None:
            raise ValueError("completed actions cannot include an error")
        if self.status is not ActionStatus.COMPLETED and self.error is None:
            raise ValueError("non-completed actions require an error")
        return self


class CapabilityResult(BaseModel):
    """A successful capability return value before executor normalization."""

    model_config = ConfigDict(extra="forbid")

    output: Any | None = None
