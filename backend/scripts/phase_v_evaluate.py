"""Create zero-step baselines and evaluate Phase V arithmetic campaigns.

All outputs are generated by local ULTRON checkpoints.  The direct set is
drawn only from the target release's held-out test partition; the remaining
families deliberately use structures absent from the training curriculum.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

from app.foundation.data import PackedShardSequenceDataset
from app.foundation.generation import GenerationConfig, UltronGenerator
from app.foundation.model import UltronModelConfig
from app.foundation.phase_v import grade_addition, wilson_interval
from app.foundation.tokenizer import UltronTokenizer
from app.foundation.training import FoundationTrainer, TrainingConfig

DIRECT_PATTERN = re.compile(r"ADD (\d+) (\d+) = (\d+)")
FAMILIES = ("direct", "surface", "structural", "counterfactual", "compositional")


def model_config(tokenizer: UltronTokenizer, *, random_seed: int = 17) -> UltronModelConfig:
    return UltronModelConfig(
        model_name="ultron-phase-u-1.35m",
        version="phase-u-v1",
        vocab_size=tokenizer.vocab_size,
        hidden_size=160,
        num_layers=4,
        num_heads=4,
        intermediate_size=640,
        max_sequence_length=64,
        random_seed=random_seed,
    )


def _direct_examples(release_dir: Path, count: int = 24) -> list[dict[str, str]]:
    """Select held-out source examples across operand/carry buckets."""
    buckets: dict[tuple[int, int], list[tuple[int, int, int]]] = {}
    for line in (release_dir / "test.jsonl").read_text(encoding="utf-8").splitlines():
        match = DIRECT_PATTERN.search(json.loads(line)["content"])
        if not match:
            continue
        left, right, total = map(int, match.groups())
        key = (len(str(left)), int((left % 10 + right % 10) >= 10))
        buckets.setdefault(key, []).append((left, right, total))
    chosen: list[tuple[int, int, int]] = []
    keys = sorted(buckets)
    position = 0
    while len(chosen) < count and any(buckets.values()):
        key = keys[position % len(keys)]
        if buckets[key]:
            chosen.append(buckets[key].pop(0))
        position += 1
    return [
        {
            "id": f"direct-{index:03d}",
            "family": "direct",
            "prompt": f"Arithmetic lesson. ADD {left} {right} =",
            "expected": str(total),
            "source_partition": "TARGET_TEST",
        }
        for index, (left, right, total) in enumerate(chosen)
    ]


def build_suite(release_dir: Path) -> list[dict[str, str]]:
    direct = _direct_examples(release_dir)
    values = [(1000 + index * 37, 500 + index * 29) for index in range(24)]
    surface = [
        {
            "id": f"surface-{index:03d}",
            "family": "surface",
            "prompt": f"What is {left} plus {right}? Answer:",
            "expected": str(left + right),
            "source_partition": "TARGET_TEST_REPHRASE",
        }
        for index, (left, right, _) in enumerate(
            (int(item["prompt"].split()[3]), int(item["prompt"].split()[4]), int(item["expected"]))
            for item in direct
        )
    ]
    structural = [
        {
            "id": f"structural-{index:03d}",
            "family": "structural",
            "prompt": f"Arithmetic lesson. ADD {left} {right} =",
            "expected": str(left + right),
            "source_partition": "OUTSIDE_TRAIN_OPERAND_RANGE",
        }
        for index, (left, right) in enumerate(values)
    ]
    counterfactual = [
        {
            "id": f"counterfactual-{index:03d}",
            "family": "counterfactual",
            "prompt": f"Calculate {right} + {left} =",
            "expected": str(left + right),
            "source_partition": "OUTSIDE_TRAIN_TEMPLATE_AND_RANGE",
        }
        for index, (left, right) in enumerate(values)
    ]
    compositional = [
        {
            "id": f"compositional-{index:03d}",
            "family": "compositional",
            "prompt": f"ADD {left} {right} {index + 3} =",
            "expected": str(left + right + index + 3),
            "source_partition": "THREE_OPERAND_UNSEEN_STRUCTURE",
        }
        for index, (left, right) in enumerate(values)
    ]
    return [*direct, *surface, *structural, *counterfactual, *compositional]


def baseline(root: Path, run_id: str, seed: int) -> Path:
    manifest = json.loads((root / "source-manifest.json").read_text(encoding="utf-8"))
    release = manifest["releases"]["general"]
    tokenizer = UltronTokenizer(root / "tokenizer")
    config = TrainingConfig(
        run_id=f"{run_id}-zero",
        model_id="ultron-phase-u-1.35m",
        steps=160_000,
        batch_size=2,
        learning_rate=3e-4,
        warmup_steps=1_600,
        checkpoint_every=160_000,
        tokens_target=20_480_000,
        dataset_release_id=release["release_id"],
        dataset_manifest_sha256=release["manifest_sha256"],
        mixture_seed=20260912,
        seed=seed,
    )
    return FoundationTrainer(root / "runs" / run_id).initialize_from_scratch(
        model_config=model_config(tokenizer, random_seed=seed),
        tokenizer=tokenizer,
        config=config,
    )


def _general_validation(root: Path) -> PackedShardSequenceDataset:
    manifest = json.loads((root / "source-manifest.json").read_text(encoding="utf-8"))
    paths = [
        Path(item["path"])
        for item in manifest["packed"]["general"]["shards"]
        if item["split"] == "validation"
    ]
    return PackedShardSequenceDataset(paths, expected_width=65, include_loss_mask=True)


def evaluate(root: Path, run_id: str) -> None:
    run_root = root / "runs" / run_id
    candidate_root = run_root / "models" / "base" / run_id
    zero = run_root / "models" / "base" / f"{run_id}-zero" / "checkpoint-000000"
    if not zero.exists():
        raise FileNotFoundError(f"Missing zero-step baseline: {zero}")
    tokenizer = UltronTokenizer(root / "tokenizer")
    model = UltronModelConfig.model_validate_json(
        (candidate_root / "model_config.json").read_text(encoding="utf-8")
    )
    suite = build_suite(root / "corpora" / "releases" / "phase-v-addition-v1")
    suite_path = root / "evaluation-suite.json"
    if suite_path.exists() and json.loads(suite_path.read_text(encoding="utf-8")) != suite:
        raise ValueError("Phase V evaluation suite is immutable.")
    if not suite_path.exists():
        suite_path.write_text(json.dumps(suite, indent=2) + "\n", encoding="utf-8")
    validation = _general_validation(root)
    trainer = FoundationTrainer(run_root)
    checkpoint_names = ["checkpoint-000000", *[f"checkpoint-{step:06d}" for step in (1600, 8000, 16000, 40000, 80000, 120000, 160000)]]
    checkpoints = [zero, *[candidate_root / name for name in checkpoint_names[1:]]]
    rows: list[dict[str, object]] = []
    for checkpoint in checkpoints:
        generator = UltronGenerator(checkpoint, tokenizer, model)
        generated: list[dict[str, object]] = []
        for item in suite:
            result = generator.generate(
                item["prompt"], GenerationConfig(max_new_tokens=16, temperature=0)
            )
            score = grade_addition(output=result.text, expected=item["expected"])
            generated.append(
                {
                    **item,
                    "output": result.text,
                    "status": result.status.value,
                    "answer_score": score.answer,
                    "syntax_score": score.syntax,
                }
            )
        scores = {
            family: sum(
                float(item["answer_score"])
                for item in generated
                if item["family"] == family
            )
            / len([item for item in generated if item["family"] == family])
            for family in FAMILIES
        }
        successes = int(sum(float(item["answer_score"]) for item in generated))
        low, high = wilson_interval(successes, len(generated))
        loss, perplexity = trainer.evaluate_checkpoint(
            checkpoint=checkpoint,
            model_config=model,
            tokenizer=tokenizer,
            sequences=validation,
        )
        rows.append(
            {
                "checkpoint": checkpoint.name,
                "checkpoint_path": str(checkpoint.resolve()),
                "scores": scores,
                "successes": successes,
                "n": len(generated),
                "wilson_low": low,
                "wilson_high": high,
                "general_validation_loss": loss,
                "general_validation_perplexity": perplexity,
                "generations": generated,
            }
        )
    (run_root / "capability-curve.json").write_text(
        json.dumps(rows, indent=2) + "\n", encoding="utf-8"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=Path("data/phase-v-e2e"))
    parser.add_argument("--run-id", required=True)
    parser.add_argument("--seed", type=int, default=17)
    parser.add_argument("--create-zero", action="store_true")
    parser.add_argument("--evaluate", action="store_true")
    args = parser.parse_args()
    root = args.root.resolve()
    if not args.create_zero and not args.evaluate:
        parser.error("Specify --create-zero, --evaluate, or both.")
    if args.create_zero:
        print(baseline(root, args.run_id, args.seed))
    if args.evaluate:
        evaluate(root, args.run_id)


if __name__ == "__main__":
    main()
